const langButtons = document.querySelectorAll('.lang-btn');
const translateItems = document.querySelectorAll('[data-i18n]');
const translatePlaceholders = document.querySelectorAll('[data-i18n-placeholder]');

function setLanguage(lang) {
  const selected = translations[lang] || translations.ru;
  translateItems.forEach((element) => {
    const text = selected[element.getAttribute('data-i18n')];
    if (text) element.textContent = text;
  });
  translatePlaceholders.forEach((element) => {
    const text = selected[element.getAttribute('data-i18n-placeholder')];
    if (text) element.setAttribute('placeholder', text);
  });
  document.documentElement.lang = lang;
  langButtons.forEach((button) => {
    button.classList.toggle('active', button.dataset.lang === lang);
  });
  localStorage.setItem('sheyx-proger-lang', lang);
}

langButtons.forEach((button) => {
  button.addEventListener('click', () => setLanguage(button.dataset.lang));
});

setLanguage(localStorage.getItem('sheyx-proger-lang') || 'ru');